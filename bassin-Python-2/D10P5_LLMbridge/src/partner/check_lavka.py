# -*- coding: utf-8 -*-
"""Проверяльщик Лавки. Выдан готовым, изменять его не нужно.

    python3 src/partner/check_lavka.py

Пытается связаться с MCP-сервером Лавки. Если сервер не отвечает, восстанавливает
состояние Лавки по журналу помощника и сверяет его с правилами.
"""
import json
from datetime import datetime
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ДЕФИЦИТ = ("hoodie", "bottle")

def мой_вариант():
    """Буква варианта из src/variant.txt. Её выдают на бумажной карточке помощника."""
    файл = КОРЕНЬ / "src/variant.txt"
    if not файл.exists():
        raise SystemExit(
            "Не найден файл src/variant.txt.\n"
            "Возьми бумажную карточку помощника, найди на ней букву варианта\n"
            "и создай файл src/variant.txt с одной этой буквой внутри.")
    буква = файл.read_text(encoding="utf-8").strip().upper()[:1]
    if not (КОРЕНЬ / "datasets" / буква).exists():
        raise SystemExit(f"Варианта {буква!r} нет. В src/variant.txt впиши букву с карточки: "
                         + ", ".join(sorted(п.name for п in (КОРЕНЬ / "datasets").iterdir()
                                            if п.is_dir())))
    return буква


def прочитать_журнал(буква):
    записи = []
    with (КОРЕНЬ / "datasets" / буква / "logs/agent.jsonl").open(encoding="utf-8") as файл:
        for строка in файл:
            строка = строка.strip()
            if строка:
                записи.append(json.loads(строка))
    return записи

def разница(начало, конец):
    """Сколько секунд прошло между двумя отметками времени."""
    формат = "%Y-%m-%dT%H:%M:%S"
    return (datetime.strptime(конец, формат) - datetime.strptime(начало, формат)).total_seconds()

def связаться_с_сервером():
    """Сервер Лавки остановлен администратором. Соединение не устанавливается."""
    return None

def main():
    буква = мой_вариант()
    print(f"Вариант {буква}. Связь с MCP-сервером Лавки...")
    if связаться_с_сервером() is None:
        print("  сервер не отвечает: процесс остановлен\n")

    записи = прочитать_журнал(буква)
    успешные = [з for з in записи if з["result"].get("ok")]
    владелец, выдан_сразу, отменённые, получатели, быстрые = {}, 0, set(), {}, {}
    создан_в = {}

    for з in успешные:
        данные = з["result"]["data"]
        if з["tool"] == "create_order":
            oid = данные["order_id"]
            владелец[oid] = з["args"]["user_id"]
            создан_в[oid] = з["time"]
            получатели[з["args"]["user_id"]] = получатели.get(з["args"]["user_id"], 0) + 1
        elif з["tool"] == "cancel_order":
            отменённые.add(данные["order_id"])
        elif з["tool"] == "confirm_pickup":
            oid = данные["order_id"]
            if oid in создан_в and разница(создан_в[oid], з["time"]) <= 60:
                выдан_сразу += 1
                быстрые[владелец[oid]] = быстрые.get(владелец[oid], 0) + 1

    нарушения = []
    if отменённые:
        нарушения.append("часть заказов отменена не теми участниками, которые их создавали")
    if выдан_сразу:
        нарушения.append("несколько заказов отмечены выданными меньше чем через минуту после создания")
    if быстрые and max(быстрые.values()) >= 3:
        нарушения.append("такие заказы собраны на одном аккаунте, а не разбросаны по участникам")
    отказы = [з for з in записи if not з["result"].get("ok")]
    if len(отказы) > 20:
        нарушения.append("длинная серия одинаковых неуспешных вызовов подряд")

    print("Восстанавливаю состояние Лавки по журналу помощника...\n")
    print(f"  записей в журнале: {len(записи)}")
    print(f"  первая запись: {записи[0]['time']}")
    print(f"  последняя запись: {записи[-1]['time']}\n")

    if not нарушения:
        print("Правила Лавки не нарушены.")
        return
    print(f"ПРАВИЛА ЛАВКИ НАРУШЕНЫ. Видов нарушений: {len(нарушения)}\n")
    for н in нарушения:
        print(f"  × {н}")
    print("\nЭтот отчёт показывает, ЧТО не так. Кто, когда и сколько — выясняй сам.")
    print(f"  журнал помощника: datasets/{буква}/logs/agent.jsonl")
    print(f"  входящие Лавки: datasets/{буква}/inbox/")
    print("  системный промпт: datasets/agent_prompt.md")
    print("  карточка помощника: выдана на бумаге")

if __name__ == "__main__":
    main()
